// Builds the inventory of an official schema set and the files generated from it:
//   src/generated/inventory.json   every element path, type, enumeration and cardinality
//   src/generated/enums.ts         string-literal unions for every enumeration (never typed by hand)
//   src/generated/schema-sets.ts   the files of each known set and their SHA-256
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { elementPaths, type ElementPath } from "./paths.ts";
import { readSchema, type Enumeration, type SchemaDoc } from "./xsd.ts";

export interface SchemaSetInput {
  /** e.g. "carf-v1.5-2025-07" */
  readonly id: string;
  /** Folder holding the set's files, as copied from the official OECD ZIP. */
  readonly dir: string;
  readonly rootSchema: string;
  readonly rootElement: string;
  /** Prefix for generated enum names, to keep sets apart ("" for the CARF set). */
  readonly enumPrefix: string;
}

export interface InventorySet {
  readonly id: string;
  readonly rootSchema: string;
  readonly rootElement: string;
  readonly enumPrefix: string;
  readonly files: readonly { readonly name: string; readonly sha256: string }[];
  readonly schemas: readonly SchemaDoc[];
  readonly elementPaths: readonly ElementPath[];
}

export interface Inventory {
  readonly format: 1;
  readonly sets: readonly InventorySet[];
}

export function readSchemaSet(input: SchemaSetInput): InventorySet {
  const schemas: SchemaDoc[] = [];
  const queue = [input.rootSchema];
  const seen = new Set<string>();
  while (queue.length > 0) {
    const file = queue.shift();
    if (file === undefined || seen.has(file)) {
      continue;
    }
    seen.add(file);
    const schema = readSchema(join(input.dir, file), file);
    schemas.push(schema);
    queue.push(...schema.imports.map((imported) => imported.schemaLocation));
  }
  const files = schemas.map((schema) => ({
    name: schema.file,
    sha256: createHash("sha256")
      .update(readFileSync(join(input.dir, schema.file)))
      .digest("hex"),
  }));
  return {
    id: input.id,
    rootSchema: input.rootSchema,
    rootElement: input.rootElement,
    enumPrefix: input.enumPrefix,
    files,
    schemas,
    elementPaths: elementPaths(schemas, input.rootElement),
  };
}

export function buildInventory(inputs: readonly SchemaSetInput[]): Inventory {
  return { format: 1, sets: inputs.map(readSchemaSet) };
}

export function inventoryJson(inventory: Inventory): string {
  return `${JSON.stringify(inventory, null, 2)}\n`;
}

interface EnumSource {
  readonly name: string;
  readonly origin: string;
  readonly documentation: string | undefined;
  readonly values: readonly Enumeration[];
}

/** "ExchangeType_EnumType" → "ExchangeType"; "currCode_Type" → "CurrCode". */
export function friendlyName(xsdName: string, prefix: string): string {
  const base = xsdName.replace(/_EnumType$/, "").replace(/_Type$/, "");
  return `${prefix}${base.charAt(0).toUpperCase()}${base.slice(1)}`;
}

function enumSources(set: InventorySet): EnumSource[] {
  const sources: EnumSource[] = [];
  for (const schema of set.schemas) {
    const prefix =
      Object.entries(schema.namespaces).find(
        ([key, namespace]) => key !== "" && namespace === schema.targetNamespace,
      )?.[0] ?? "";
    for (const type of schema.simpleTypes) {
      if (type.name !== undefined && type.enumerations.length > 0) {
        sources.push({
          name: friendlyName(type.name, set.enumPrefix),
          origin: `${prefix}:${type.name}`,
          documentation: type.documentation,
          values: type.enumerations,
        });
      }
    }
    for (const type of schema.complexTypes) {
      for (const attribute of type.attributes) {
        const values = attribute.inlineType?.enumerations ?? [];
        if (type.name !== undefined && values.length > 0) {
          sources.push({
            name: `${set.enumPrefix}${attribute.name}`,
            origin: `${prefix}:${type.name}/@${attribute.name}`,
            documentation: attribute.documentation,
            values,
          });
        }
      }
    }
  }
  return sources;
}

function literal(value: string): string {
  return JSON.stringify(value);
}

function propertyKey(value: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : literal(value);
}

export function enumsModule(inventory: Inventory): string {
  const lines = [
    "// GENERATED by scripts/xsd-inventory.ts from the official OECD XSD files. Do not edit.",
    "// Values and labels are copied from the xsd:enumeration values and their xsd:documentation.",
    "",
  ];
  const names = new Set<string>();
  for (const set of inventory.sets) {
    for (const source of enumSources(set)) {
      if (names.has(source.name)) {
        throw new Error(`Duplicate generated enum name ${source.name}`);
      }
      names.add(source.name);
      const doc = source.documentation === undefined ? "" : ` ${source.documentation}`;
      lines.push(`/** ${source.origin} (${set.id}).${doc} */`);
      lines.push(`export const ${source.name} = [`);
      for (const entry of source.values) {
        lines.push(`  ${literal(entry.value)},`);
      }
      lines.push("] as const;");
      lines.push(`export type ${source.name} = (typeof ${source.name})[number];`);
      if (source.values.every((entry) => entry.documentation !== undefined)) {
        lines.push(
          `export const ${source.name}Labels: Readonly<Record<${source.name}, string>> = {`,
        );
        for (const entry of source.values) {
          lines.push(`  ${propertyKey(entry.value)}: ${literal(entry.documentation ?? "")},`);
        }
        lines.push("};");
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

export function schemaSetsModule(inventory: Inventory): string {
  const lines = [
    "// GENERATED by scripts/xsd-inventory.ts from the official OECD XSD files. Do not edit.",
    "// SHA-256 of each file, computed from the files the inventory was generated from.",
    "",
    "export interface KnownSchemaSet {",
    "  readonly id: string;",
    "  readonly rootSchema: string;",
    "  readonly rootElement: string;",
    "  readonly targetNamespace: string;",
    "  readonly version: string | undefined;",
    "  readonly files: readonly { readonly name: string; readonly sha256: string }[];",
    "}",
    "",
    "export const KNOWN_SCHEMA_SETS: readonly KnownSchemaSet[] = [",
  ];
  for (const set of inventory.sets) {
    const root = set.schemas[0];
    lines.push("  {");
    lines.push(`    id: ${literal(set.id)},`);
    lines.push(`    rootSchema: ${literal(set.rootSchema)},`);
    lines.push(`    rootElement: ${literal(set.rootElement)},`);
    lines.push(`    targetNamespace: ${literal(root?.targetNamespace ?? "")},`);
    lines.push(
      `    version: ${root?.version === undefined ? "undefined" : literal(root.version)},`,
    );
    lines.push("    files: [");
    for (const file of set.files) {
      lines.push(`      { name: ${literal(file.name)}, sha256: ${literal(file.sha256)} },`);
    }
    lines.push("    ],");
    lines.push("  },");
  }
  lines.push("];", "");
  return lines.join("\n");
}
